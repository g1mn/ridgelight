// tools/build-data.mjs
// Reads data/ and verify/ JSON files along with web/i18n/*.json,
// and produces web/gen/data.js and web/gen/i18n.js.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const repoRoot = process.cwd();
const outDirArg = process.argv[2];
const outDir = outDirArg ? path.resolve(repoRoot, outDirArg) : path.join(repoRoot, 'web', 'gen');

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

function readJsonIfExists(relPath) {
  const fullPath = path.join(repoRoot, relPath);
  if (!fs.existsSync(fullPath)) {
    return { data: null, hash: null, relPath };
  }
  const buf = fs.readFileSync(fullPath);
  try {
    const data = JSON.parse(buf.toString('utf-8'));
    return { data, hash: sha256(buf), relPath };
  } catch (err) {
    console.error(`Warning: Failed to parse JSON at ${relPath}: ${err.message}`);
    return { data: null, hash: sha256(buf), relPath, error: err.message };
  }
}

function readJsonDirIfExists(relDir) {
  const fullDir = path.join(repoRoot, relDir);
  const result = {};
  const sources = {};
  if (!fs.existsSync(fullDir)) {
    return { result, sources };
  }
  const entries = fs.readdirSync(fullDir, { withFileTypes: true });
  for (const entry of entries) {
    if (entry.isFile() && entry.name.endsWith('.json')) {
      const relPath = path.join(relDir, entry.name);
      const res = readJsonIfExists(relPath);
      if (res.data) {
        const id = path.basename(entry.name, '.json');
        result[id] = res.data;
        sources[relPath] = res.hash;
      }
    }
  }
  return { result, sources };
}

const sources = {};

// 1. Sites
const sitesRes = readJsonIfExists('data/sites.json');
let sitesData = null;
if (sitesRes.data) {
  sitesData = sitesRes.data;
  sources['data/sites.json'] = sitesRes.hash;
}

// 2. Horizon
const horizonRes = readJsonDirIfExists('data/horizon');
const horizonData = horizonRes.result;
Object.assign(sources, horizonRes.sources);

// 3. Tracks
const tracksRes = readJsonDirIfExists('data/tracks');
const tracksData = tracksRes.result;
Object.assign(sources, tracksRes.sources);

// 4. Map values
const mapValuesRes = readJsonIfExists('data/map-values.json');
let mapValuesData = null;
if (mapValuesRes.data) {
  mapValuesData = mapValuesRes.data;
  sources['data/map-values.json'] = mapValuesRes.hash;
}

// 5. Verification summaries
const l1aRes = readJsonIfExists('verify/l1a-summary.json');
let l1aData = null;
if (l1aRes.data) {
  l1aData = l1aRes.data;
  sources['verify/l1a-summary.json'] = l1aRes.hash;
}

const l1bRes = readJsonIfExists('verify/l1b-summary.json');
let l1bData = null;
if (l1bRes.data) {
  l1bData = l1bRes.data;
  sources['verify/l1b-summary.json'] = l1bRes.hash;
}

const m1Res = readJsonIfExists('verify/m1-summary.json');
let m1Data = null;
if (m1Res.data) {
  m1Data = m1Res.data;
  sources['verify/m1-summary.json'] = m1Res.hash;
}

const lwData = {
  sources,
  sites: sitesData,
  horizon: horizonData,
  tracks: tracksData,
  map_values: mapValuesData,
  verify: {
    l1a: l1aData,
    l1b: l1bData,
    m1: m1Data
  }
};

// 6. i18n
const i18nDir = path.join(repoRoot, 'web', 'i18n');
const lwI18n = {};
if (fs.existsSync(i18nDir)) {
  const i18nEntries = fs.readdirSync(i18nDir, { withFileTypes: true });
  for (const entry of i18nEntries) {
    if (entry.isFile() && entry.name.endsWith('.json')) {
      const lang = path.basename(entry.name, '.json');
      const relPath = path.join('web', 'i18n', entry.name);
      const res = readJsonIfExists(relPath);
      if (res.data) {
        lwI18n[lang] = res.data;
      }
    }
  }
}

// Ensure output directory exists
fs.mkdirSync(outDir, { recursive: true });

// Check em-dash
const dataJsonStr = JSON.stringify(lwData);
if (dataJsonStr.includes('\u2014')) {
  throw new Error('Forbidden em-dash (U+2014) detected in data payload.');
}

const dataContent = `// generated by tools/build-data.mjs, do not edit\nglobalThis.LW_DATA = ${dataJsonStr};\n`;
const i18nContent = `// generated by tools/build-data.mjs, do not edit\nglobalThis.LW_I18N = ${JSON.stringify(lwI18n)};\n`;

const dataOutPath = path.join(outDir, 'data.js');
const i18nOutPath = path.join(outDir, 'i18n.js');

fs.writeFileSync(dataOutPath, dataContent, 'utf-8');
fs.writeFileSync(i18nOutPath, i18nContent, 'utf-8');

const dataSize = fs.statSync(dataOutPath).size;
const i18nSize = fs.statSync(i18nOutPath).size;

console.log(`Generated ${dataOutPath} (${dataSize} bytes)`);
console.log(`Generated ${i18nOutPath} (${i18nSize} bytes)`);

if (dataSize > 5 * 1024 * 1024) {
  throw new Error(`data.js exceeds 5 MB limit: ${dataSize} bytes`);
}
